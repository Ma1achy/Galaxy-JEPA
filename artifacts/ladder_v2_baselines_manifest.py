"""Ladder subset (a) on the six baselines (baselines_comparison.md §D) → docs/ladder_v2_baselines/manifest.yaml.

    .venv/bin/python artifacts/ladder_v2_baselines_manifest.py
    .venv/bin/python artifacts/ladder_v2_run.py --manifest docs/ladder_v2_baselines/manifest.yaml --plan

§D's six entries per encoder, in its order and with ladder v2's own commands, estimates and expected
outputs (`ladder_v2_manifest.Builder`, so nothing about an entry is re-stated here): E3 `o1_matched`,
the E7 link to the untrained seeds 1–2 bank, E5 `p2_ladder`, E7 `r0`, E5 `s2_verify`, E5 `t1_ladder`.
Encoders in §5.3's order: MoCo s0, MAE s0, MoCo s1, MAE s1, MoCo s2, MAE s2, each the re-export made by
`ladder_v2_baselines_export.py`.

**The shared inputs carry over and are not re-run (§D).** Ladder v2 built them once from architecture,
pixels and split, which the baselines share with A1 (config equal outside `objective`): the K = 30
untrained bank (E4) and A1's untrained seeds 1–2 bank (E7). They are inputs from another manifest, so
here they are pins (SHA-1, checked before every entry) rather than entry inputs.

**One deviation from §D's wording, declared.** §D names outputs `runs/ladder_v2/<experiment>/<encoder>/`;
ladder v2 itself writes one directory per encoder (`runs/ladder_v2/<encoder>/`), because the drivers read
each other's records by name from one `LADDER_OUT`. The baselines follow ladder v2's layout. Plumbing
only: no entry, input or statistic changes.

Investigation code: terse, excluded from lint/CI.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ladder_v2_manifest as M  # noqa: E402

TAGS = ("moco_s0", "mae_s0", "moco_s1", "mae_s1", "moco_s2", "mae_s2")
ROOT = "runs/ladder_v2"
SHARED = {  # ladder v2's own, not re-run: pinned
    "E4": f"{ROOT}/shared/p1_untrained_bank.json",
    "E7": f"{ROOT}/a1/r_untrained_seeds.npz",
}
EXCLUDED = {  # §D, "Not in (a)"
    "E7 r1–r3, E11 U2, E12 U3, E15 V3, E20 AA1": "option (b), not chosen",
    "E24 DD SAEs": "option (c), not chosen",
    "E0–E2, E8, E10, E14, E16–E19, E22, E23, E26": "outside subset (a)",
    "E4 untrained bank, E7 untrained seeds bank": "shared, built by ladder v2; pinned, not re-run",
}
OUT = M.REPO / "docs/ladder_v2_baselines/manifest.yaml"


class Baselines(M.Builder):
    def encoder(self, enc: str) -> None:
        a, ckpt = self.add, M.ENCODERS[enc]
        r = ["--checkpoint", ckpt]
        e3 = a(f"E3.o1_matched.{enc}", exp="E3", enc=enc, script="o1_matched.py", args=[*r, "--tag", "o1"],
               heavy="mps", est_h=0.6, expect=["o1_embeddings.npz", "o1_matched.json"])
        e7 = a(f"E7.r_bank_link.{enc}", exp="E7", enc=enc, inputs=[e3],
               link={"src": SHARED["E7"], "dst": "r_untrained_seeds.npz"})
        base = [e3, e7]
        p2 = a(f"E5.p2_ladder.{enc}", exp="E5", enc=enc, script="p2_ladder.py", args=r, inputs=base,
               heavy="mps", est_h=3.0, expect=["p2_ladder.json"])
        r0 = a(f"E7.r0.{enc}", exp="E7", enc=enc, script="r_nonlinear.py", args=[*r, "--stages", "r0"],
               inputs=[*base, p2], est_h=0.5, expect=["r_r0.json"])
        s2 = a(f"E5.s2_verify.{enc}", exp="E5", enc=enc, script="s2_verify.py", inputs=[*base, p2, r0],
               heavy="mps", est_h=3.0, expect=["s2_ladder.json", "s2_noise.npz"])
        a(f"E5.t1_ladder.{enc}", exp="E5", enc=enc, script="t1_ladder.py", inputs=[*base, p2, s2],
          est_h=4.0, expect=["t1_ladder.json"])
        for e in self.entries[-6:]:
            e["pins"].update({p: self._pin(p) for p in SHARED.values()})


def main() -> None:
    M.ENCODERS.clear()
    M.ENCODERS.update({t: f"{ROOT}/encoders/{t}.pt" for t in TAGS})
    M.COMMON_ENV["LADDER_UNTRAINED_BANK"] = SHARED["E4"]
    b = Baselines(ROOT)
    for t in TAGS:
        if (M.REPO / b.out(t)).exists():
            raise SystemExit(f"baselines manifest: {b.out(t)} exists; each encoder starts from an empty directory")
        b.encoder(t)
    ids = [e["id"] for e in b.entries]
    assert len(set(ids)) == len(ids)
    for e in b.entries:
        assert all(i in ids[: ids.index(e["id"])] for i in e["inputs"]), e["id"]
    doc = {"version": 1, "root": ROOT, "common_env": M.COMMON_ENV,
           "scope": "baselines_comparison.md §D option (a): existence subset, six baseline encoders",
           "shared_pinned": SHARED, "excluded": EXCLUDED, "not_implemented": M.NOT_IMPLEMENTED,
           "entries": b.entries}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("# Generated by artifacts/ladder_v2_baselines_manifest.py — do not edit by hand.\n"
                   + yaml.safe_dump(doc, sort_keys=False, width=110, allow_unicode=True))
    print(f"baselines manifest: {len(b.entries)} entries → {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
